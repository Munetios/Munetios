export function normalizeHelpLocale(locale) {
  const candidate = String(locale || "en").replaceAll("_", "-");
  if (candidate in helpLocales) return candidate;
  const language = candidate.split("-")[0];
  return language in helpLocales ? language : "en";
}

export function getHelpCopy(locale) {
  const normalized = normalizeHelpLocale(locale);
  return { ...en, ...(translations[normalized] || {}) };
}

export function validateHelpTranslations() {
  const requiredKeys = Object.keys(en).sort();
  return Object.fromEntries(
    Object.keys(helpLocales).map((locale) => [
      locale,
      requiredKeys.filter((key) => !(key in translations[locale])),
    ]),
  );
}
