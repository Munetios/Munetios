const aliases = { co: "fr", fur: "it", gl: "es" };
const files = (await readdir(directory)).filter((file) =>
  file.endsWith(".json"),
);
for (const file of files) {
  const locale = file.replace(/\.json$/u, "");
  const prefix = locale.split("_")[0];
  const pack = translations[aliases[prefix] || prefix];
  if (!pack) throw new Error(`Missing translations for ${file}`);
  const path = join(directory, file);
  const data = JSON.parse(await readFile(path, "utf8"));
  keys.forEach((key, index) => {
    data[key] = pack[index];
  });
  const sorted = Object.fromEntries(
    Object.entries(data).sort(([left], [right]) => left.localeCompare(right)),
  );
  await writeFile(path, `${JSON.stringify(sorted, null, 2)}\n`, "utf8");
}

console.log(
  `Updated ${keys.length} Education policy keys in ${files.length} locales.`,
);
