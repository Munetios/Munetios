#!/usr/bin/env node
/*
 * Builds omniwrite/sheets/sheets-shell.css.
 *
 * The spreadsheet editor is a page inside OmniWrite (#sheetEditorApp) that reuses the document
 * editor's navbar, toolbar, and phone layout. OmniWrite styles those through "#editorContent ..."
 * selectors, so this script copies every rule that targets #editorContent (and the phone bottom
 * bar) and points it at the spreadsheet page, with the "sh"-prefixed ids sheets.js uses.
 *
 * Run after changing omniwrite.css, mobile-layout.css, or omniwrite-v4.css:
 *   node scripts/build-sheets-shell-css.cjs
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..', 'omniwrite');
const sources = ['omniwrite.css', 'mobile-layout.css', 'omniwrite-v4.css'];
const sheetsJs = fs.readFileSync(path.join(root, 'sheets', 'sheets.js'), 'utf8');
const idList = sheetsJs.match(/const PREFIXED_IDS = new Set\(\[([\s\S]*?)\]\)/);
if (!idList) throw new Error('PREFIXED_IDS not found in sheets.js');
const prefixed = new Set([...idList[1].matchAll(/'([^']+)'/g)].map(m => m[1]));
const mapId = id => (id === 'editorContent' ? 'sheetEditorApp' : prefixed.has(id) ? 'sh' + id.charAt(0).toUpperCase() + id.slice(1) : id);

// Selectors worth copying: the editor page, or the phone bottom bar and its Tools button.
const TARGET = /#editorContent\b|#mobileEditorToolbar\b|#mobileEditorToolsBtn\b/;
// ".page:not(#editorContent)" means "every other page", so mentions inside :not() don't count.
const wanted = selector => TARGET.test(selector.replace(/:not\([^()]*\)/g, ''));
// A shared group like ":is(.sidebar, .toolbar, #editorContent .navbar)" also styles other UI, so only
// its editor items are kept: ":is(#editorContent .navbar)".
function narrowGroups(selector) {
    return selector.replace(/:(is|where)\(([^()]*)\)/g, (match, kind, list) => {
        const items = list.split(',').map(s => s.trim());
        if (items.length < 2 || !items.some(item => TARGET.test(item))) return match;
        return ':' + kind + '(' + items.filter(item => TARGET.test(item)).join(', ') + ')';
    });
}
const remap = selector => narrowGroups(selector).replace(/#([A-Za-z][\w-]*)/g, (m, id) => '#' + mapId(id));

// Minimal CSS walker: handles comments, strings, nested @media/@supports/@container blocks.
function stripComments(css) {
    return css.replace(/\/\*[\s\S]*?\*\//g, '');
}
function splitSelectors(text) {
    const parts = [];
    let depth = 0, current = '';
    for (const ch of text) {
        if (ch === '(' || ch === '[') depth++;
        if (ch === ')' || ch === ']') depth--;
        if (ch === ',' && depth === 0) { parts.push(current); current = ''; continue; }
        current += ch;
    }
    parts.push(current);
    return parts.map(s => s.trim()).filter(Boolean);
}
function findBlockEnd(css, open) {
    let depth = 0, quote = null;
    for (let i = open; i < css.length; i++) {
        const ch = css[i];
        if (quote) { if (ch === '\\') { i++; continue; } if (ch === quote) quote = null; continue; }
        if (ch === '"' || ch === "'") { quote = ch; continue; }
        if (ch === '{') depth++;
        else if (ch === '}') { depth--; if (depth === 0) return i; }
    }
    return css.length - 1;
}
function walk(css) {
    const out = [];
    let i = 0;
    while (i < css.length) {
        const open = css.indexOf('{', i);
        if (open < 0) break;
        const prelude = css.slice(i, open).trim();
        const close = findBlockEnd(css, open);
        const body = css.slice(open + 1, close);
        if (/^@(media|supports|container|layer)\b/.test(prelude)) {
            const inner = walk(body);
            if (inner.length) out.push(prelude + ' {\n' + inner.map(rule => '    ' + rule.replace(/\n/g, '\n    ')).join('\n') + '\n}');
        } else if (!prelude.startsWith('@')) {
            const selectors = splitSelectors(prelude.replace(/^[;}\s]+/, '')).filter(wanted);
            if (selectors.length) out.push(selectors.map(remap).join(',\n') + ' {' + body.replace(/\s+$/, '') + '\n}');
        }
        i = close + 1;
    }
    return out;
}

const chunks = sources.map(file => {
    const rules = walk(stripComments(fs.readFileSync(path.join(root, file), 'utf8')));
    return rules.length ? `/* ---- from ${file} (${rules.length}) ---- */\n` + rules.join('\n') : '';
}).filter(Boolean);

const header = `/*
 * GENERATED by scripts/build-sheets-shell-css.cjs. Do not edit by hand.
 * OmniWrite's document-editor shell rules (#editorContent) applied to the spreadsheet page
 * (#sheetEditorApp), so the navbar, toolbar, and phone layout match the document editor exactly.
 */
`;
const target = path.join(root, 'sheets', 'sheets-shell.css');
fs.writeFileSync(target, header + chunks.join('\n\n') + '\n');
console.log('wrote', path.relative(process.cwd(), target), fs.statSync(target).size, 'bytes');
